import AppKit
import ApplicationServices
import os

final class EventTapController {
    static let syntheticEventTag: Int64 = 0x57494E4D // "WINM"

    private let logger = Logger(subsystem: "com.riyazjpersonalteam.WinManager", category: "EventTap")

    var onScroll: ((CGEvent) -> CGEvent?)?
    var onKeyEvent: ((CGEvent, CGEventType) -> CGEvent?)?
    var onFlagsChanged: ((CGEvent) -> Void)?
    var onHotkey: ((Bool) -> Bool)?
    var onModifierReleased: (() -> Void)?
    var onMouseDown: ((CGEvent) -> Bool)?

    private var eventTap: CFMachPort?
    private var runLoopSource: CFRunLoopSource?

    var isActive: Bool {
        eventTap != nil
    }

    func start() {
        guard eventTap == nil else { return }

        guard PermissionsManager.hasInputMonitoring else {
            logger.warning("Cannot create Event Tap: Input Monitoring permission not granted. Requesting...")
            PermissionsManager.requestInputMonitoringPrompt()
            return
        }

        let mask = (CGEventMask(1) << CGEventType.scrollWheel.rawValue)
            | (CGEventMask(1) << CGEventType.keyDown.rawValue)
            | (CGEventMask(1) << CGEventType.keyUp.rawValue)
            | (CGEventMask(1) << CGEventType.flagsChanged.rawValue)
            | (CGEventMask(1) << CGEventType.leftMouseDown.rawValue)

        let callback: CGEventTapCallBack = { _, type, event, userInfo in
            guard let userInfo else { return Unmanaged.passUnretained(event) }
            let controller = Unmanaged<EventTapController>.fromOpaque(userInfo).takeUnretainedValue()

            // Handle event tap disablement gracefully
            if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
                controller.logger.notice("Event tap disabled by system (type: \(type.rawValue)), re-enabling...")
                controller.reenableTap()
                return Unmanaged.passUnretained(event)
            }

            // Ignore synthetic events generated by WinManager to prevent infinite recursion
            if event.getIntegerValueField(.eventSourceUserData) == EventTapController.syntheticEventTag {
                return Unmanaged.passUnretained(event)
            }

            switch type {
            case .scrollWheel:
                let modifiedEvent = controller.onScroll?(event) ?? event
                return Unmanaged.passUnretained(modifiedEvent)

            case .leftMouseDown:
                if UserDefaults.standard.bool(forKey: "enableDockClicks"),
                   controller.onMouseDown?(event) == true {
                    return nil
                }
                return Unmanaged.passUnretained(event)

            case .keyDown, .keyUp:
                var currentEvent: CGEvent? = event

                // 1. Route to background utilities (Cmd+X, Quit Protection)
                if let handler = controller.onKeyEvent {
                    currentEvent = handler(currentEvent!, type)
                }
                guard let finalEvent = currentEvent else { return nil }

                // 2. Route to App Switcher (Cmd+Tab)
                if type == .keyDown {
                    let keyCode = finalEvent.getIntegerValueField(.keyboardEventKeycode)
                    let flags = finalEvent.flags
                    if keyCode == 48, flags.contains(.maskCommand) {
                        let reverse = flags.contains(.maskShift)
                        if UserDefaults.standard.bool(forKey: "enableAppSwitcher"),
                           controller.onHotkey?(reverse) == true {
                            return nil
                        }
                    }
                }
                return Unmanaged.passUnretained(finalEvent)

            case .flagsChanged:
                controller.onFlagsChanged?(event)
                let flags = event.flags
                if !flags.contains(.maskCommand) {
                    controller.onModifierReleased?()
                }
                return Unmanaged.passUnretained(event)

            default:
                return Unmanaged.passUnretained(event)
            }
        }

        let userInfo = Unmanaged.passUnretained(self).toOpaque()
        guard let tap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: mask,
            callback: callback,
            userInfo: userInfo
        ) else {
            logger.error("Failed to create CGEvent tap. Check Input Monitoring permissions.")
            return
        }

        eventTap = tap
        runLoopSource = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
        if let runLoopSource {
            CFRunLoopAddSource(CFRunLoopGetMain(), runLoopSource, .commonModes)
            CGEvent.tapEnable(tap: tap, enable: true)
            logger.info("CGEvent tap successfully created and enabled.")
        }
    }

    func retryIfNeeded() {
        if eventTap == nil {
            start()
        }
    }

    func stop() {
        if let source = runLoopSource {
            CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
        }
        if let eventTap {
            CFMachPortInvalidate(eventTap)
        }
        runLoopSource = nil
        eventTap = nil
        logger.info("CGEvent tap stopped.")
    }

    fileprivate func reenableTap() {
        if let eventTap {
            CGEvent.tapEnable(tap: eventTap, enable: true)
        }
    }
}

